import assert from "node:assert/strict";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { test } from "node:test";
import { SCHEMA_VERSION, openClubDatabase } from "../src/lib/database";
import { splitStatements, translateStatement } from "../src/lib/db/postgres";
import { demoPassword } from "../src/lib/db/migrations";
import { DuplicateMemberError } from "../src/lib/errors";

/**
 * Dialect translation is always tested. The live journey runs only when
 * MODE_TEST_DATABASE_URL points at a PostgreSQL server (npm run postgres:up, then
 * MODE_TEST_DATABASE_URL=postgres://mode:mode@127.0.0.1:5432/mode npm test).
 */
const url = process.env.MODE_TEST_DATABASE_URL;

test("statement translation covers every SQLite construct the modules use", () => {
  assert.equal(translateStatement("PRAGMA foreign_keys = ON"), null);
  assert.equal(translateStatement("PRAGMA journal_mode = WAL;"), null);
  assert.equal(translateStatement("PRAGMA user_version"), 'SELECT COALESCE(MAX(version), 0)::int AS user_version FROM "schema_migrations"');
  assert.equal(translateStatement("PRAGMA user_version = 12"), 'INSERT INTO "schema_migrations" (version) VALUES (12) ON CONFLICT (version) DO NOTHING');
  assert.match(translateStatement("PRAGMA table_info(expense_receipts)")!, /information_schema\.columns .* table_name = 'expense_receipts'/);
  assert.equal(translateStatement("BEGIN IMMEDIATE"), "BEGIN");
  assert.equal(translateStatement("SAVEPOINT sp_1"), "SAVEPOINT sp_1");
  assert.equal(translateStatement("SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = ?"),
    "SELECT 1 FROM information_schema.tables WHERE table_schema = current_schema() AND table_name = $1");
  assert.equal(translateStatement("INSERT OR IGNORE INTO membership_reminders (a, b) VALUES (?, ?)"),
    "INSERT INTO membership_reminders (a, b) VALUES ($1, $2) ON CONFLICT DO NOTHING");
  assert.equal(translateStatement("UPDATE events SET registered = MAX(0, registered - ?) WHERE id = ?"),
    "UPDATE events SET registered = GREATEST(0, registered - $1) WHERE id = $2");
  assert.equal(translateStatement("SELECT * FROM transactions ORDER BY occurred_at DESC, rowid DESC"),
    "SELECT * FROM transactions ORDER BY occurred_at DESC, seq DESC");
  assert.equal(translateStatement("SELECT * FROM members WHERE club_id = ? ORDER BY joined_at DESC, name COLLATE NOCASE, id"),
    "SELECT * FROM members WHERE club_id = $1 ORDER BY joined_at DESC, LOWER(name), id");
  assert.equal(translateStatement("SELECT d.new_expires_on AS 'Membership expires' FROM dues_payments d WHERE d.id = ?"),
    'SELECT d.new_expires_on AS "Membership expires" FROM dues_payments d WHERE d.id = $1');
  assert.equal(translateStatement("SELECT id FROM expenses WHERE event_id IS ? AND paid_at = ?"),
    "SELECT id FROM expenses WHERE event_id IS NOT DISTINCT FROM $1 AND paid_at = $2");
  assert.match(translateStatement("CREATE TABLE t (id TEXT PRIMARY KEY, n INTEGER NOT NULL, e TEXT NOT NULL COLLATE NOCASE UNIQUE)")!,
    /n bigint NOT NULL, e citext NOT NULL UNIQUE,\s+seq bigint GENERATED BY DEFAULT AS IDENTITY/);
  assert.equal(translateStatement("ALTER TABLE t ADD COLUMN c INTEGER NOT NULL DEFAULT 0 CHECK (c >= 0)"),
    "ALTER TABLE t ADD COLUMN c bigint NOT NULL DEFAULT 0 CHECK (c >= 0)");
  assert.equal(translateStatement("SELECT 'a;b' AS x WHERE y = ?"), "SELECT 'a;b' AS x WHERE y = $1");
  assert.deepEqual(splitStatements("CREATE TABLE a (x TEXT);\n  INSERT INTO a VALUES ('p;q');\n"), ["CREATE TABLE a (x TEXT)", "INSERT INTO a VALUES ('p;q')"]);
});

test("PostgreSQL runtime: migrate from empty, run every money-moving flow, reconcile", { skip: !url && "MODE_TEST_DATABASE_URL not set" }, () => {
  const receiptsDir = mkdtempSync(join(tmpdir(), "mode-pg-receipts-"));
  const clock = { now: new Date("2026-10-10T08:00:00.000Z") };
  const db = openClubDatabase(url!, { now: () => new Date(clock.now), receiptsDir, resetSchema: true });
  try {
    assert.deepEqual(db.health(), { status: "ok", database: "postgres", schemaVersion: SCHEMA_VERSION });
    const actor = (email: string) => db.getActor(db.login({ email, password: demoPassword() }).token)!;
    const admin = actor("lead@example.com");
    const organizer = actor("organizer@example.com");
    const treasurer = actor("treasurer@example.com");
    const active = actor("active@example.com");

    // identity + constraint mapping (23505 -> SQLITE_CONSTRAINT_UNIQUE -> DuplicateMemberError)
    const member = db.createMemberAs(organizer, { name: "O'Brien \\ Démo", email: "obrien@example.com" });
    assert.throws(() => db.createMember({ name: "Dup", email: "OBRIEN@example.com" }), DuplicateMemberError);
    db.setPassword(admin, member.id, "obrien-pass-2026");
    const obrien = db.getActor(db.login({ email: "obrien@example.com", password: "obrien-pass-2026" }).token)!;
    assert.equal(obrien.memberId, member.id);

    // dues -> ledger
    const dues = db.dues.recordDues(treasurer, { memberId: member.id, reference: "UPI-0001" });
    assert.equal(dues.created, true);
    assert.equal(db.dues.recordDues(treasurer, { memberId: member.id, reference: "UPI-0001" }).created, false);

    // events: hold, expiry, confirm, scan
    const event = db.events.createEvent(organizer, { title: "Hack Night", description: "", startsAt: "2026-10-20T12:00:00.000Z", venue: "Lab 3", capacity: 1, memberPricePaise: 5000, guestPricePaise: 8000, status: "published" });
    const ticket = db.events.bookTicket(active, event.id);
    assert.equal(ticket.status, "pending_payment");
    assert.throws(() => db.events.bookGuestTicket(admin.clubId, event.id, { name: "Guest", email: "guest@example.com" }), /sold out/);
    clock.now = new Date(clock.now.getTime() + 31 * 60_000);
    assert.throws(() => db.events.confirmTicket(treasurer, ticket.id, { reference: "UPI-0002" }), /Hold expired/);
    // The failed confirmation rolled its hold release back (same as SQLite); the next booking releases it again.
    const rebooked = db.events.bookTicket(active, event.id);
    assert.equal(rebooked.status, "pending_payment");
    assert.equal(db.events.requireEvent(admin.clubId, event.id).available, 0);
    assert.equal(db.events.confirmTicket(treasurer, rebooked.id, { reference: "UPI-0002" }).created, true);
    assert.equal(db.events.scan(actor("volunteer@example.com"), event.id, { credential: rebooked.shortCode }).outcome, "admitted");
    assert.equal(db.events.scan(actor("volunteer@example.com"), event.id, { credential: rebooked.shortCode }).outcome, "already_checked_in");

    // merchandise: stock reservation, confirm, fulfil
    const product = db.merchandise.createProduct(organizer, { name: "Hoodie", description: "", pricePaise: 79900, memberPricePaise: 69900, variants: [{ size: "M", stock: 1 }] });
    const order = db.merchandise.createOrder(active, { variantId: product.variants[0].id, quantity: 1 });
    assert.equal(order.unitPricePaise, 69900, "member pricing from membershipState");
    assert.throws(() => db.merchandise.createOrder(obrien, { variantId: product.variants[0].id, quantity: 1 }), /out of stock/);
    db.merchandise.confirmOrder(treasurer, order.id, { reference: "UPI-0003" });
    assert.equal(db.merchandise.fulfilOrder(organizer, order.id).status, "fulfilled");

    // expenses: receipt, submit, approve, pay -> ledger
    const data = Buffer.from("%PDF-1.4 synthetic test receipt");
    const receipt = db.saveReceipt(active, { filename: "bill.pdf", mimeType: "application/pdf", sizeBytes: data.length, data });
    const expense = db.submitExpense(active, { amountPaise: 12345, purpose: "Snacks for hack night", receiptId: receipt.id, eventId: event.id });
    db.approveExpense(treasurer, expense.id);
    assert.equal(db.payExpense(treasurer, expense.id, "NEFT-0004").status, "paid");

    // announcements, reminders, tasks
    const publication = db.announcements.publish(organizer, { idempotencyKey: "welcome-1", title: "Welcome", body: "Hello 👋" });
    assert.equal(publication.created, true);
    assert.equal(db.announcements.publish(organizer, { idempotencyKey: "welcome-1", title: "Welcome", body: "Hello 👋" }).created, false);
    assert.ok(db.dues.sendRenewalReminders(organizer, 365).sent >= 1);
    assert.equal(db.dues.sendRenewalReminders(organizer, 365).sent, 0, "second run is a no-op");
    const task = db.createTask(organizer, { title: "Set up desk", assigneeId: active.memberId, eventId: event.id, dueAt: "2026-10-19T00:00:00.000Z" });
    assert.equal(db.updateTaskStatus(active, task.id, "done").status, "done");

    // ledger: every source posted once, nothing missing or mismatched
    const report = db.ledger.reconcile();
    assert.deepEqual({ orphans: report.orphans, duplicates: report.duplicates, unsourced: report.unsourced, missing: report.missing, mismatched: report.mismatched },
      { orphans: [], duplicates: [], unsourced: 0, missing: [], mismatched: [] });
    assert.equal(report.balancePaise, 185000 + 50000 + 5000 + 69900 - 12345);
    assert.equal(db.getLedgerSummary(treasurer).balancePaise, report.balancePaise);

    // reopening without reset keeps the data and does not re-run migrations
    db.close();
    const again = openClubDatabase(url!, { now: () => new Date(clock.now), receiptsDir });
    try {
      assert.equal(again.getMembers().length, 10);
      assert.equal(again.ledger.reconcile().entries, report.entries);
    } finally {
      again.close();
    }
  } finally {
    try { db.close(); } catch { /* closed above */ }
    rmSync(receiptsDir, { recursive: true, force: true });
  }
});
