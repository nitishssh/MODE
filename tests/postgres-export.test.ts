import assert from "node:assert/strict";
import { test } from "node:test";
import { DatabaseSync } from "node:sqlite";
import { SCHEMA_VERSION, migrate } from "../src/lib/db/migrations";
import {
  PG_CHECK_VIOLATION,
  PG_FOREIGN_KEY_VIOLATION,
  PG_UNIQUE_VIOLATION,
  SQLITE_TO_POSTGRES_ERRCODE,
  isPostgresConstraintError,
  orderTablesByDependency,
  postgresExport,
  postgresSchema,
  quoteLiteral,
  readSchemaObjects,
  toPostgresPlaceholders,
  translateTableDdl,
} from "../src/lib/db/postgres";
import { SQLITE_CONSTRAINT_CHECK, SQLITE_CONSTRAINT_FOREIGNKEY, SQLITE_CONSTRAINT_UNIQUE } from "../src/lib/db/core";

const FIXED_NOW = new Date("2026-10-10T08:00:00.000Z");

function migratedMemoryDb(): DatabaseSync {
  process.env.MODE_DEMO_PASSWORD ??= "postgres-test-placeholder";
  const db = new DatabaseSync(":memory:");
  db.exec("PRAGMA foreign_keys = ON;");
  migrate(db, FIXED_NOW);
  return db;
}

/** Count the VALUES tuples emitted for one table; each tuple starts a line with two spaces and "(". */
function exportedRows(script: string, table: string): number {
  const section = script.split(`-- ${table}: `)[1]?.split("\n-- ")[0] ?? "";
  return section.split("\n").filter((line) => /^  \(/.test(line)).length;
}

test("placeholders are renumbered for PostgreSQL without touching string literals", () => {
  assert.equal(toPostgresPlaceholders("a = ? AND b IN (?, ?) AND c = 'why?'"), "a = $1 AND b IN ($2, $3) AND c = 'why?'");
  assert.equal(toPostgresPlaceholders("no params"), "no params");
});

test("literals are quoted the PostgreSQL way", () => {
  assert.equal(quoteLiteral(null), "NULL");
  assert.equal(quoteLiteral(42), "42");
  assert.equal(quoteLiteral(42n), "42");
  assert.equal(quoteLiteral("O'Brien \\ line\nbreak"), "'O''Brien \\ line\nbreak'");
  assert.equal(quoteLiteral(new Uint8Array([0xde, 0xad])), "'\\xdead'::bytea");
});

test("SQLite constraint codes map onto PostgreSQL SQLSTATEs", () => {
  assert.equal(SQLITE_TO_POSTGRES_ERRCODE[SQLITE_CONSTRAINT_UNIQUE], PG_UNIQUE_VIOLATION);
  assert.equal(SQLITE_TO_POSTGRES_ERRCODE[SQLITE_CONSTRAINT_CHECK], PG_CHECK_VIOLATION);
  assert.equal(SQLITE_TO_POSTGRES_ERRCODE[SQLITE_CONSTRAINT_FOREIGNKEY], PG_FOREIGN_KEY_VIOLATION);
  const unique = Object.assign(new Error("duplicate key"), { code: "23505" });
  assert.equal(isPostgresConstraintError(unique), true);
  assert.equal(isPostgresConstraintError(unique, PG_UNIQUE_VIOLATION), true);
  assert.equal(isPostgresConstraintError(unique, PG_CHECK_VIOLATION), false);
  assert.equal(isPostgresConstraintError(new Error("plain")), false);
});

test("table DDL is translated: bigint, citext, boolean arithmetic cast, seq identity column", () => {
  const members = translateTableDdl("CREATE TABLE members (id TEXT PRIMARY KEY, email TEXT NOT NULL COLLATE NOCASE UNIQUE, n INTEGER NOT NULL)");
  assert.match(members, /email citext NOT NULL UNIQUE/);
  assert.match(members, /n bigint NOT NULL/);
  assert.match(members, /seq bigint GENERATED BY DEFAULT AS IDENTITY\n\s+\);$/);
  assert.doesNotMatch(members, /COLLATE NOCASE/);

  const tickets = translateTableDdl("CREATE TABLE t (a TEXT, b TEXT, CHECK ((a IS NULL) + (b IS NULL) = 1))");
  assert.match(tickets, /CHECK \(\(\(a IS NULL\)::int \+ \(b IS NULL\)::int\) = 1\)/);
});

test("tables are ordered so every foreign key target is created first", () => {
  const db = migratedMemoryDb();
  try {
    const tables = orderTablesByDependency(readSchemaObjects(db).filter((o) => o.type === "table"));
    const position = new Map(tables.map((t, i) => [t.name, i]));
    const before = (parent: string, child: string) => assert.ok(position.get(parent)! < position.get(child)!, `${parent} must precede ${child}`);
    before("clubs", "sessions");
    before("members", "sessions");
    before("people", "members");
    before("members", "announcements");
    before("announcements", "notifications");
    before("announcements", "outbox_messages");
    before("events", "tickets");
    before("products", "product_variants");
    before("product_variants", "merch_orders");
    before("expense_receipts", "expenses");
    before("transactions", "legacy_ledger_imports");
    before("members", "whatsapp_preferences");
    before("members", "whatsapp_deliveries");
    before("clubs", "whatsapp_groups");
    assert.equal(tables.length, 24);
  } finally {
    db.close();
  }
});

test("the PostgreSQL schema document covers every table and records the schema version", () => {
  const db = migratedMemoryDb();
  try {
    const ddl = postgresSchema(db, SCHEMA_VERSION);
    for (const table of readSchemaObjects(db).filter((o) => o.type === "table")) {
      assert.ok(new RegExp(`CREATE TABLE(?: IF NOT EXISTS)? "?${table.name}"? \\(`).test(ddl), `missing CREATE TABLE ${table.name}`);
    }
    assert.match(ddl, /CREATE EXTENSION IF NOT EXISTS citext;/);
    assert.match(ddl, new RegExp(`INSERT INTO "schema_migrations" \\(version\\) VALUES \\(${SCHEMA_VERSION}\\);`));
    assert.match(ddl, /CREATE UNIQUE INDEX tickets_member_event_live_idx ON tickets \(event_id, member_id\)\s+WHERE member_id IS NOT NULL/);
    assert.doesNotMatch(ddl, /^PRAGMA/m);
    assert.doesNotMatch(ddl, /^\s+\w+ INTEGER\b/m);
  } finally {
    db.close();
  }
});

test("the export carries every seeded row, escapes awkward text and restores identity sequences", () => {
  const db = migratedMemoryDb();
  try {
    db.prepare("INSERT INTO clubs (id, name, description, created_at) VALUES (?, ?, ?, ?)").run("club-quote", "Quote's \\ Club\nSecond line", "", FIXED_NOW.toISOString());
    const script = postgresExport(db, { version: SCHEMA_VERSION, generatedAt: FIXED_NOW.toISOString() });

    assert.ok(script.startsWith("-- MODE PostgreSQL export"));
    assert.match(script, /^BEGIN;$/m);
    assert.match(script, /^COMMIT;\n$/m);
    assert.ok(script.includes("'Quote''s \\ Club\nSecond line'"), "single quotes doubled, backslash and newline kept literally");

    for (const table of readSchemaObjects(db).filter((o) => o.type === "table")) {
      const count = Number((db.prepare(`SELECT COUNT(*) AS n FROM "${table.name}"`).get() as { n: number }).n);
      assert.equal(exportedRows(script, table.name), count, `${table.name} row count`);
      if (count) assert.ok(script.includes(`  PERFORM setval(pg_get_serial_sequence('"${table.name}"', 'seq'), (SELECT MAX(seq) FROM "${table.name}"));`));
    }
    assert.equal(exportedRows(script, "members"), 9);
    assert.equal(exportedRows(script, "clubs"), 2);
    assert.match(script, /INSERT INTO "members" \("id", "name", "email", .*"seq"\) VALUES/);
    assert.ok(/DO \$\$ BEGIN\n(  PERFORM setval[^\n]+\n)+END \$\$;/.test(script), "identity sequences restored in one DO block");
    assert.match(script, /-- \d+ row\(s\) across 24 table\(s\)\./);
  } finally {
    db.close();
  }
});

test("export options: replace prefixes drops in reverse order, skipData keeps DDL but no rows", () => {
  const db = migratedMemoryDb();
  try {
    const script = postgresExport(db, { version: SCHEMA_VERSION, replace: true, skipData: ["sessions", "members"], generatedAt: FIXED_NOW.toISOString() });
    const drops = [...script.matchAll(/DROP TABLE IF EXISTS "(\w+)" CASCADE;/g)].map((m) => m[1]);
    assert.equal(drops[0], "schema_migrations");
    assert.ok(drops.indexOf("sessions") < drops.indexOf("members"), "children dropped before parents");
    assert.ok(script.indexOf('DROP TABLE IF EXISTS "members"') < script.search(/CREATE TABLE "?members"? \(/));
    assert.match(script, /-- members: data skipped on request/);
    assert.equal(exportedRows(script, "members"), 0);
    assert.equal(exportedRows(script, "clubs"), 1);
  } finally {
    db.close();
  }
});
